"""elements.json -> renderer/eclipse_data.c (contacts and types too)"""
import json, math, os
from check import local, central, ev, E
def root(f, a, b, it=60):
    fa = f(a)
    for _ in range(it):
        m = (a+b)/2; fm = f(m)
        if (fm > 0) == (fa > 0): a, fa = m, fm
        else: b = m
    return (a+b)/2
def solar_extra(e):
    def g(t):  # >0 when penumbra misses the Earth (with a small flattening allowance)
        h = (t-e['t0'])/3600; return math.hypot(ev(e['x'],h), ev(e['y'],h)) - (1.003 + ev(e['l1'],h))
    tm = e['tmax']
    p1 = root(g, tm - 5*3600, tm); p4 = root(g, tm, tm + 5*3600)
    # central: axis on Earth
    ts = [t for t in range(int(p1), int(p4), 30) if central(e, t)]
    typ = 'P'
    if ts:
        signs = set()
        for t in ts:
            la, lo = central(e, t); signs.add(local(e, t, la, lo)[2] < 0)
        typ = 'T' if signs == {True} else 'A' if signs == {False} else 'H'
    return p1, p4, (ts[0] if ts else 0), (ts[-1] if ts else 0), typ
def lunar_extra(e):
    def d(t, which):
        h = (t-e['t0'])/3600; x=ev(e['x'],h); y=ev(e['y'],h); sm=ev(e['sm'],h)
        r = {'p': ev(e['rp'],h)+sm, 'u': ev(e['ru'],h)+sm, 't': ev(e['ru'],h)-sm}[which]
        return math.hypot(x, y) - r
    tm = e['tmax']; out = []
    for w in 'put':
        if d(tm, w) < 0: out += [root(lambda t: d(t,w), tm-5*3600, tm), root(lambda t: d(t,w), tm, tm+5*3600)]
        else: out += [0, 0]
    return out
def arr(c, n): c = list(c) + [0.0]*(n-len(c)); return '{ ' + ', '.join('%.10g' % v for v in c[:n]) + ' }'
L = ['/* Generated by tools/eclgen (JPL DE421 via Skyfield): do not edit.',
     ' * Solar: Besselian elements; lunar: Moon vs Earth\'s shadow. Polynomials',
     ' * in UT hours from t0 (UT), so no Delta-T is needed. */',
     '#include "eclipse.h"', '', 'const pic_ecl_solar_t pic_ecl_solar[] = {']
for e in E['solar']:
    p1, p4, c1, c2, typ = solar_extra(e)
    L.append('    { "%s", \'%s\', %d, %d, %d, %d, %d, %.6f,' % (e['date'], typ, round(e['t0']), round(e['tmax']), round(p1), round(p4), (c1 and c2) and 1, e['gamma']))
    L.append('      %s, %s, %s, %s,' % (arr(e['x'],4), arr(e['y'],4), arr(e['d'],3), arr(e['mu'],2)))
    L.append('      %s, %s, %.10g, %.10g, %d, %d },' % (arr(e['l1'],3), arr(e['l2'],3), e['tf1'], e['tf2'], round(c1), round(c2)))
L += ['};', 'const int pic_ecl_nsolar = (int)(sizeof(pic_ecl_solar) / sizeof(pic_ecl_solar[0]));', '',
      'const pic_ecl_lunar_t pic_ecl_lunar[] = {']
for e in E['lunar']:
    c = lunar_extra(e)
    L.append('    { "%s", %d, %.4f, %d, %d, { %s },' % (e['date'], e['kind'], e['umag'], round(e['t0']), round(e['tmax']), ', '.join(str(round(v)) for v in c)))
    L.append('      %s, %s, %s, %s, %s, %s, %s },' % (arr(e['x'],4), arr(e['y'],4), arr(e['ru'],3), arr(e['rp'],3), arr(e['sm'],3), arr(e['dec'],3), arr(e['gha'],2)))
L += ['};', 'const int pic_ecl_nlunar = (int)(sizeof(pic_ecl_lunar) / sizeof(pic_ecl_lunar[0]));', '']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'renderer', 'eclipse_data.c'), 'w').write('\n'.join(L))
print('ok')
