def place(lat, lon):
    return '%d°%s %d°%s' % (round(abs(lat)), 'N' if lat >= 0 else 'S', round(abs(lon)), 'E' if lon >= 0 else 'W')
items = []
for e in E['solar']:
    p1, p4, c1, c2, typ = solar_extra(e)
    key = 'S' + e['date']
    name = {'T': 'Total', 'A': 'Annular', 'H': 'Hybrid', 'P': 'Partial'}[typ] + ' solar'
    c = central(e, e['tmax'])
    where = NOTES.get(key)
    if not where:
        where = ('over ' + place(*c)) if c else ('Arctic' if e['gamma'] > 0 else 'Antarctic') + ' partial'
    best = 0
    for t in range(int(p1), int(p4), 120):
        m, L1, L2, z = local(e, t, *HOME)
        if z > 0 and m < L1:
            best = max(best, __import__('check').obscuration(m, L1, L2))
    home = (' · home %d%%' % round(best*100)) if best > 0.005 else ''
    items.append((e['tmax'], key, '%s · %s · %s%s' % (e['date'], name, where, home)))
for e in E['lunar']:
    c = lunar_extra(e)
    if not c[0]: continue
    key = 'L' + e['date']
    name = ['Penumbral', 'Partial', 'Total'][e['kind']] + ' lunar'
    extra = NOTES.get(key, '')
    if c[4]:
        d = int(c[5] - c[4]) // 60
        extra = (extra + ', ' if extra else '') + 'totality %dh%02dm' % (d // 60, d % 60) if not extra else extra
    h = (e['tmax'] - e['t0'])/3600
    dec = math.radians(ev(e['dec'], h)); lon = -ev(e['gha'], h)
    la = math.radians(HOME[0])
    up = math.sin(la)*math.sin(dec) + math.cos(la)*math.cos(dec)*math.cos(math.radians(HOME[1] - lon)) > 0
    items.append((e['tmax'], key, '%s · %s%s%s' % (e['date'], name, (' · ' + extra) if extra else '', ' · Moon up at home' if up else '')))
